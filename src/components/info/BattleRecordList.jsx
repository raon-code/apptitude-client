function StatusIcon({ status }) {
  const path =
    status === 'tie'
      ? FLAT_MOUTH
      : status === 'received'
        ? HAPPY_MOUTH
        : SAD_MOUTH;

  return (
    <svg
      width='20'
      height='21'
      viewBox='0 0 20 21'
      fill='none'
      aria-hidden='true'
    >
      <path
        fillRule='evenodd'
        clipRule='evenodd'
        d={path}
        fill={STATUS_COLORS[status]}
      />
    </svg>
  );
}

export default function BattleRecordList({ type, records }) {
  if (records.length === 0) {
    return <Empty>아직 대결 기록이 없어요.</Empty>;
  }

  return (
    <List>
      {records.map((record) => {
        const status =
          type === 'tie' ? 'tie' : record.gift ? 'received' : 'pending';
        const caption =
          type === 'tie'
            ? '대결에서 비겼어요.'
            : (CAPTIONS[type]?.[status] ?? '');

        return (
          <Row key={record.id} to={`/result/${record.id}`} state={{ type }}>
            <BattleAvatar />
            <Body>
              <div>
                <Name>{record.name}</Name>님과 대결!
              </div>
              <Status>
                <StatusIcon status={status} />
                {caption}
              </Status>
            </Body>
          </Row>
        );
      })}
    </List>
  );
}
